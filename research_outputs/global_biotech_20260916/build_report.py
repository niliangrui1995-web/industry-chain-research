# ---------------------------------------------------------------- 引用机制

_cite_n: dict[str, int] = {}
_cite_targets: dict[str, list[str]] = {eid: [] for eid in EV}


def C(eid: str) -> str:
    """生成一个唯一引用锚点 + 证据徽章 + 定位索引链接。"""
    assert eid in EV, f"unknown evidence id {eid}"
    _cite_n[eid] = _cite_n.get(eid, 0) + 1
    cid = f"cite-{eid}-{_cite_n[eid]}"
    _cite_targets[eid].append(cid)
    return (
        f'<span id="{cid}"></span>'
        f'<button class="source-link evidence-button" type="button" data-evidence-id="{eid}" '
        f'aria-label="查看证据 {eid} 详情">证据 {eid} · 查看依据</button>'
        f'<a class="source-link" href="#evidence-{eid}">定位证据索引 ↓</a>'
    )


def JC(label: str, body: str) -> str:
    return f'<div class="judge-card"><div class="jc-t">{label}</div><div class="jc-b">{body}</div></div>'


